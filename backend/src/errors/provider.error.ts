import { HTTP_ERROR_CODE } from '@self-review/contracts';

export class ProviderError extends Error {
	constructor(
		readonly code:
			| 'PROVIDER_CREDENTIALS_INVALID'
			| 'PROVIDER_UNAVAILABLE'
			| 'PROVIDER_RATE_LIMITED'
			| 'PROVIDER_RESPONSE_INVALID'
			| 'PROVIDER_RESPONSE_LIMIT'
			| 'PROVIDER_FIELD_LIMIT'
			| 'PROVIDER_SCOPE_CHANGED'
			| 'PAGINATION_LOOP',
		readonly retryable = false,
	) {
		super(code);
	}
}

export const PROVIDER_ERROR_CODES = new Set<string>([
	HTTP_ERROR_CODE.PROVIDER_CREDENTIALS_INVALID,
	HTTP_ERROR_CODE.PROVIDER_UNAVAILABLE,
	HTTP_ERROR_CODE.PROVIDER_RATE_LIMITED,
	HTTP_ERROR_CODE.PROVIDER_RESPONSE_INVALID,
	HTTP_ERROR_CODE.PROVIDER_RESPONSE_LIMIT,
	HTTP_ERROR_CODE.PROVIDER_FIELD_LIMIT,
	HTTP_ERROR_CODE.PROVIDER_SCOPE_CHANGED,
	'PAGINATION_LOOP',
]);
